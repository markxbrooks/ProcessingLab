#!/usr/bin/env bash
# Populate a synthetic known_indexed corpus from the analytical C++ fixtures.
#
# This unblocks Phase C differentials until a real indexed image set exists.
# Outputs are labelled SYNTHETIC — not ipmosflm Fortran captures.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IMG_DIR="${ROOT}/testdata/images/known_indexed"
OUT_DIR="${ROOT}/testdata/oracle/known_indexed"
CLI="${MOSFLM_CPP_CLI:-${ROOT}/build/mosflm_cpp_cli}"

mkdir -p "${IMG_DIR}" "${OUT_DIR}"

if [[ ! -x "${CLI}" ]]; then
  echo "error: mosflm_cpp_cli not found at ${CLI}" >&2
  echo "Build first: cmake --build ${ROOT}/build --target mosflm_cpp_cli" >&2
  exit 1
fi

"${CLI}" predict-still "${OUT_DIR}/predict_still.dump"
"${CLI}" predict-osc "${OUT_DIR}/predict_osc.dump"

cat > "${IMG_DIR}/geometry.txt" <<'EOF'
# SYNTHETIC known_indexed geometry (analytical stills / osc fixtures)
# Cell (thaumatin-like): 58 58 150 90 90 90
# Orientation: identity (UB from cell, R = I)
# Detector: λ=1.0 Å, distance=250 mm, pixel=0.172 mm, 1475×1679
# Beam centre: (0, 0) mm in beam-relative frame
# Stills: φ=0, dmin=3.5 Å, ewald_tol=0.0025 Å⁻¹
# Osc: φ ∈ [0, 0.5]°, dmin=5.0 Å, φ step=0.05°
EOF

cat > "${IMG_DIR}/ipmosflm.in" <<'EOF'
! Template for a future real ipmosflm capture (SYNTHETIC params below).
! Replace IMAGE paths with real frames under this directory, then run:
!   ./tools/capture_ipmosflm_oracle.sh
!
! WAVE 1.0
! DISTANCE 250.0
! BEAM 0.0 0.0
! PIXEL 0.172 0.172
! CELL 58.0 58.0 150.0 90.0 90.0 90.0
! MATRIX  ... (identity orientation)
! IMAGE image_001.cbf
! GO
! EXIT
EOF

cat > "${OUT_DIR}/README.md" <<EOF
# Synthetic known_indexed oracles

Generated by \`tools/generate_synthetic_known_indexed.sh\` from
\`mosflm_cpp_cli\` analytical fixtures (**not** \`bin/ipmosflm\` dumps).

| File | Source |
| ---- | ------ |
| \`predict_still.dump\` | analytical stills (n=656) |
| \`predict_osc.dump\` | analytical oscillation (n=368) |

When a real indexed dataset is available, replace these with captures from
\`capture_ipmosflm_oracle.sh\` and keep the same \`PREDICT_DUMP\` line format.
EOF

echo "Wrote ${OUT_DIR}/predict_still.dump, predict_osc.dump"
echo "Wrote ${IMG_DIR}/geometry.txt, ipmosflm.in"
